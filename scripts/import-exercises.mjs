// Copies demo frames for the curated library out of a local free-exercise-db clone,
// and regenerates src/db/exerciseFrames.ts so Metro can bundle them.
//
//   git clone --depth 1 https://github.com/yuhonas/free-exercise-db.git <dir>
//   node scripts/import-exercises.mjs <dir>
//
// Needs Node 23.6+ (imports library.ts directly).
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { LIBRARY } from '../src/db/library.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = process.argv[2];
if (!source) {
  console.error('Usage: node scripts/import-exercises.mjs <path to free-exercise-db clone>');
  process.exit(1);
}

const records = JSON.parse(readFileSync(join(source, 'dist', 'exercises.json'), 'utf8'));
const byId = new Map(records.map((r) => [r.id, r]));

const outDir = join(root, 'assets', 'exercises');
rmSync(outDir, { recursive: true, force: true });

const problems = [];
const entries = [];
for (const e of LIBRARY) {
  const record = byId.get(e.sourceId);
  if (!record) {
    problems.push(`${e.id}: no free-exercise-db record "${e.sourceId}"`);
    continue;
  }
  if (record.images.length < 2) {
    problems.push(`${e.id}: "${e.sourceId}" has ${record.images.length} image(s), need 2`);
    continue;
  }
  mkdirSync(join(outDir, e.id), { recursive: true });
  const frames = record.images.slice(0, 2).map((image, i) => {
    const from = join(source, 'exercises', image);
    if (!existsSync(from)) problems.push(`${e.id}: missing file ${image}`);
    else copyFileSync(from, join(outDir, e.id, `${i}.jpg`));
    return `require('../../assets/exercises/${e.id}/${i}.jpg')`;
  });
  entries.push(`  '${e.id}': [\n    ${frames.join(',\n    ')},\n  ],`);
}

if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}

writeFileSync(
  join(root, 'src', 'db', 'exerciseFrames.ts'),
  `// Generated by scripts/import-exercises.mjs. Do not edit by hand.
// Demo frames (start and end position) from free-exercise-db, public domain.
// Keyed by ExerciseMedia.key; Metro needs every require() to be a literal path.
export const exerciseFrames: Record<string, number[]> = {
${entries.join('\n')}
};
`,
);
console.log(`Imported ${entries.length} exercises into assets/exercises.`);
